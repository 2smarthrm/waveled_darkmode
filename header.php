  function validateRequiredInputs() {
    let isValid = true;
    let requiredAll = form.querySelectorAll("input[required], textarea[required]");

    requiredAll.forEach((input) => {
      if (!String(input.value || "").trim()) {
        isValid = false;
        input.classList.add("input-error");
      } else {
        input.classList.remove("input-error");
      }
    });

    if (!isValid) toastr.warning("Por favor, preencha todos os campos obrigatórios antes de enviar.");
    return isValid;
  }

  function collectFormData() {
    let sections = Container.querySelectorAll(".new-product-return");

    let Info = {
      company: document.querySelector("#formcompany").value.trim(),
      email: document.querySelector("#formemail").value.trim(),
      nif: document.querySelector("#formnif").value.trim(),
      phone: document.querySelector("#formphone").value.trim(),
      products: [],
    };

    for (let i = 0; i < sections.length; i++) {
      let sectionInputs = sections[i].querySelectorAll(".input");
      let DT = {};
      for (let a = 0; a < sectionInputs.length; a++) {
        const key = sectionInputs[a].getAttribute("id").split("-")[0];
        DT[key] = sectionInputs[a].value;
      }
      Info.products.push(DT);
    }

    return Info;
  }


  

  function base64ToBlob(base64, mime = "application/pdf") {
    const pure = base64.includes(",") ? base64.split(",")[1] : base64;
    const byteChars = atob(pure);
    const byteNumbers = new Array(byteChars.length);
    for (let i = 0; i < byteChars.length; i++) byteNumbers[i] = byteChars.charCodeAt(i);
    return new Blob([new Uint8Array(byteNumbers)], { type: mime });
  }

  function openAndMaybePrintPDF(pdfBlob, shouldPrint) {
    const url = URL.createObjectURL(pdfBlob);
    const w = window.open(url, "_blank");

    if (!w) {
      toastr.warning("Pop-up bloqueado. Permita pop-ups para abrir/imprimir o PDF.");
      return;
    }

    if (shouldPrint) {
      const tryPrint = () => {
        try {
          w.focus();
          w.print();
        } catch (e) {}
      };

      w.addEventListener("load", () => setTimeout(tryPrint, 400));
      setTimeout(tryPrint, 1200);
    }
  }
 

  async function sendForm({ shouldPrint = false, buttonEl }) {
    if (!validateRequiredInputs()) return;

    const originalText = buttonEl.innerHTML;
    buttonEl.disabled = true;
    buttonEl.innerHTML = "A enviar...";

    const Info = collectFormData();

    try {
      const response = await fetch(API_URL, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ dt: Info }),
      });

      if (!response.ok){
        console.log(response);
         throw new Error("HTTP " + response.status);
      }

    
      const contentType = response.headers.get("content-type") || "";
      if (contentType.includes("application/pdf")) {
        const pdfBlob = await response.blob();
        toastr.success("Mensagem enviada com sucesso!");
        openAndMaybePrintPDF(pdfBlob, shouldPrint);
        return;
      }

      
      const data = await response.json();
      toastr.success(data?.msg || "Mensagem enviada com sucesso!");

      const pdfFile = data?.pdf_base64 || data?.pdf_file;
      if (!pdfFile) {
        if (shouldPrint) toastr.warning("PDF não foi devolvido pelo servidor para impressão.");
        return;
      }

      if (typeof pdfFile === "string") {
        const blob = base64ToBlob(pdfFile, "application/pdf");
        openAndMaybePrintPDF(blob, shouldPrint);
        return;
      }

      if (pdfFile?.type === "Buffer" && Array.isArray(pdfFile?.data)) {
        const blob = new Blob([new Uint8Array(pdfFile.data)], { type: "application/pdf" });
        openAndMaybePrintPDF(blob, shouldPrint);
        return;
      }

      if (Array.isArray(pdfFile)) {
        const blob = new Blob([new Uint8Array(pdfFile)], { type: "application/pdf" });
        openAndMaybePrintPDF(blob, shouldPrint);
        return;
      }

      if (shouldPrint) toastr.warning("Formato de PDF recebido não suportado para abrir automaticamente.");
    } catch (error) {
      console.error(error);
      toastr.warning("Lamentamos, mas não foi possível enviar a sua mensagem!");
    } finally {
      buttonEl.innerHTML = originalText;
      buttonEl.disabled = false;
    }
  }
 
 
